const assert=require('node:assert/strict');
const D=require('../winkelhulp/deals.js');
const day='2026-10-27';
const bundle={name:'Jumbo Wokgroenten Chinees 400 g',status:'active',valid_from:'2026-10-21',valid_until:'2026-10-27',price:1.25,normal_price:2.49,multi_buy_quantity:2,multi_buy_price:2.49,size_label:'400 g',url:'https://www.jumbo.com/producten/test'};
assert.equal(D.categoryOf(bundle.name),'groente');
const priced=D.calc(bundle);
assert.equal(priced.required,2);
assert.equal(priced.checkout,2.49);
assert.equal(priced.each,1.245);
const found=D.choose({stores:{jumbo:[bundle,bundle]}},'jumbo',day,'groente');
assert.equal(found.length,1,'geen dubbele producten');
assert.equal(found[0].unitPrice.unit,'kg');
assert.ok(Math.abs(found[0].unitPrice.value-3.1125)<0.001);
assert.equal(D.choose({stores:{jumbo:[bundle]}},'jumbo','2026-10-28').length,0,'verlopen actie niet tonen');
assert.equal(D.choose({stores:{jumbo:[bundle]}},'jumbo',day,'vis').length,0,'categorie filter');
assert.equal(D.calc({...bundle,multi_buy_price:5.98}),null,'geen korting als bundel niet goedkoper is');
assert.equal(D.calc({...bundle,normal_price:null}),null,'ontbrekende reguliere prijs geen korting');
const regular={...bundle,name:'Lidl Scharrelkipdijreepjes shoarma 500 g',multi_buy_quantity:null,multi_buy_price:null,price:4.79,normal_price:5.99};
assert.equal(D.calc(regular).checkout,4.79,'enkelvoudige actie');
assert.equal(D.categoryOf(regular.name),'vlees');
assert.equal(D.fresh('2026-10-26T20:50:18+01:00',Date.parse('2026-10-27T18:50:18+01:00')),true);
assert.equal(D.fresh('2026-10-26T20:50:18+01:00',Date.parse('2026-10-29T10:50:18+01:00')),false);
console.log('Brede aanbiedingen: bundelprijs, datum, categorisering en veiligheid geslaagd');
